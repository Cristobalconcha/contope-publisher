/**
 * (d) Abre cada una de las cinco páginas de Basis EN EL EDITOR DE BLOQUES de wp-admin (Chrome sin ventana, con la sesión de una
 * persona) y comprueba que carga sin el aviso «bloque no válido»: ningún bloque con `isValid === false`, ninguna advertencia de
 * validación de bloques en la consola del editor y ningún bloque «sin soporte» (missing). Puede fallar: si una página guardara
 * HTML que no coincide con lo que el `save()` de un bloque produce, WordPress lo marcaría y esto lo cuenta.
 *
 *   node scripts/basis/verificar-editor.mjs
 *
 * No guarda nada (no se toca el editor). Credencial de persona: ACCESO-LOCAL.md (CLAVE_HUMANA / USUARIO_HUMANO la reemplazan).
 */
import { readFileSync } from 'node:fs';
import { abrirChrome } from '../piezas/chrome.mjs';

const SITIO = (process.env.SITIO || 'http://localhost:8894').replace(/\/+$/, '');
const clave = process.env.CLAVE_HUMANA || (readFileSync('C:/Users/Cristobal concha/wp-local-basis/ACCESO-LOCAL.md', 'utf8').match(/Contraseña:\s*(\S+)/) || [])[1];
const usuario = process.env.USUARIO_HUMANO || 'cristobal';
const [u, ...r] = readFileSync(process.env.AUTH_FILE || 'C:/Users/Cristobal concha/wp-local-basis/.credencial-mcp-local.txt', 'utf8').trim().split(':');
const AUTH = 'Basic ' + Buffer.from(u + ':' + r.join(':').replace(/\s+/g, '')).toString('base64');
const SLUGS = process.env.PAGINAS ? process.env.PAGINAS.split(',') : ['inicio', 'basis-carpas-industriales', 'preguntas-frecuentes', 'contactos', 'terminos-y-privacidad'];

let fallas = 0;
const { cdp, evaluar, dormir, cerrar, alEvento } = await abrirChrome({ ancho: 1400, alto: 900, escala: 1, movil: false });
const consola = [];
alEvento((m, p) => {
  if (m === 'Runtime.consoleAPICalled' && ['warning', 'error'].includes(p.type)) consola.push((p.args || []).map((a) => a.value || a.description || '').join(' ').slice(0, 300));
});
try {
  await cdp('Page.enable'); await cdp('Runtime.enable');
  await cdp('Page.navigate', { url: `${SITIO}/wp-login.php` });
  await dormir(2000);
  await evaluar(`(() => { document.querySelector('#user_login').value = ${JSON.stringify(usuario)}; document.querySelector('#user_pass').value = ${JSON.stringify(clave)}; document.querySelector('#wp-submit').click(); })()`);
  await dormir(3500);
  for (const slug of SLUGS) {
    const ids = await (await fetch(`${SITIO}/wp-json/wp/v2/pages?slug=${slug}&status=any&_fields=id`, { headers: { Authorization: AUTH } })).json();
    const id = ids[0]?.id;
    consola.length = 0;
    await cdp('Page.navigate', { url: `${SITIO}/wp-admin/post.php?post=${id}&action=edit` });
    let listo = false;
    for (let i = 0; i < 60 && !listo; i += 1) {
      await dormir(1000);
      listo = await evaluar(`!!(window.wp && wp.data && wp.data.select('core/block-editor') && wp.data.select('core/block-editor').getBlocks().length > 0 && wp.data.select('core/editor').getCurrentPost().id === ${id})`).catch(() => false);
    }
    await dormir(2500);
    const r2 = await evaluar(`(() => {
      const bs = wp.data.select('core/block-editor').getBlocks();
      let total = 0; const invalidos = []; const faltantes = [];
      const rec = (b, ruta) => { total += 1; if (!b.isValid) invalidos.push(ruta + ' ' + b.name); if (b.name === 'core/missing') faltantes.push(ruta); (b.innerBlocks || []).forEach((h, i) => rec(h, ruta + '.' + i)); };
      bs.forEach((b, i) => rec(b, String(i)));
      const aviso = !!document.querySelector('.block-editor-warning, .has-warning, .wp-block-missing');
      return { total, invalidos, faltantes, aviso, titulo: wp.data.select('core/editor').getEditedPostAttribute('title') };
    })()`);
    const validacion = consola.filter((c) => /Block validation|Content generated by .save|isn.t valid|invalid/i.test(c));
    const ok = r2 && r2.total > 0 && r2.invalidos.length === 0 && r2.faltantes.length === 0 && !r2.aviso && validacion.length === 0;
    if (!ok) fallas += 1;
    console.log(`${ok ? 'ok   ' : 'FALLA'} ${slug} (página ${id}): ${r2?.total ?? 0} bloques en el editor, ${r2?.invalidos?.length ?? '?'} inválidos, ${r2?.faltantes?.length ?? '?'} sin soporte, aviso en pantalla: ${r2?.aviso}, advertencias de validación en consola: ${validacion.length}`);
    for (const x of (r2?.invalidos || []).slice(0, 6)) console.log('   inválido: ' + x);
    for (const x of validacion.slice(0, 3)) console.log('   consola: ' + x);
  }
} finally { await cerrar(); }
console.log(fallas ? `\n${fallas} página(s) con problemas en el editor` : '\nlas cinco páginas cargan en el editor sin avisos de bloque no válido');
process.exit(fallas ? 1 : 0);
